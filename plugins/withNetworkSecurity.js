const RAW_NAME = "sectigo_r46";

const XML = `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="true">d-flight.it</domain>
    <trust-anchors>
      <certificates src="system" />
      <certificates src="@raw/${RAW_NAME}" />
    </trust-anchors>
  </domain-config>
</network-security-config>
`;

module.exports = function withNetworkSecurity(config) {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res");
      fs.mkdirSync(path.join(res, "xml"), { recursive: true });
      fs.mkdirSync(path.join(res, "raw"), { recursive: true });
      fs.writeFileSync(path.join(res, "xml", "network_security_config.xml"), XML);
      fs.writeFileSync(path.join(res, "raw", `${RAW_NAME}.pem`), CERT_PEM);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    return cfg;
  });
};
