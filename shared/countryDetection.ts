export interface BoundingBox {
  minLat: number;
  maxLat: number;
  minLon: number;
  maxLon: number;
}

// Liefert die grobe Bounding-Box eines Landes als Vereinigung aller
// COUNTRY_BOUNDING_BOXES-Einträge dieses ISO (manche Länder, z. B. BA/XK,
// haben mehrere Teil-Boxen). Einzige Quelle für die Radius-/Viewport-Abdeckung
// in geozoneCoverage.ts, damit Erkennung und Abdeckung dieselben Grenzen nutzen.
export function getCountryBoundingBox(iso: string): BoundingBox | undefined {
  const code = iso.toUpperCase();
  const boxes = COUNTRY_BOUNDING_BOXES.filter((b) => b.iso === code);
  if (boxes.length === 0) return undefined;
  return boxes.reduce<BoundingBox>(
    (acc, b) => ({
      minLat: Math.min(acc.minLat, b.minLat),
      maxLat: Math.max(acc.maxLat, b.maxLat),
      minLon: Math.min(acc.minLon, b.minLon),
      maxLon: Math.max(acc.maxLon, b.maxLon),
    }),
    { minLat: Infinity, maxLat: -Infinity, minLon: Infinity, maxLon: -Infinity },
  );
}

// Puffer (in Grad) um die Deutschland-Bounding-Box, der das "direkte Umland"
// abdeckt, in dem das DWD-ICON-D2-Modell (Grundlage von dipul UND BrightSky)
// noch zuverlässig ist. Bewusst konservativ: Grenzregionen wie Elsass,
// Benelux, Schweiz, Österreich, Tschechien und Westpolen bleiben damit auf
// DWD, während klar außerhalb liegende Orte (z. B. die französische
// Atlantik-/Kanalküste, ~4° westlich der DE-Grenze) als "Ausland" gelten.
const DWD_COVERAGE_BUFFER_DEG = 1.5;

// Liegt der Standort innerhalb der zuverlässigen DWD/ICON-D2-Abdeckung
// (Deutschland + direktes Umland)? dipul (ICON-D2) und BrightSky beruhen beide
// auf dem deutschen ICON-D2-Modell; am Modellrand und darüber hinaus werden die
// Werte unzuverlässig. Diese Funktion ist die einzige Quelle für die
// Wetterquellen-Reihenfolge (innen → dipul/BrightSky zuerst; außen → Open-Meteo
// zuerst, das im Ausland automatisch lokale Modelle wie AROME in FR nutzt).
export function isWithinDwdCoverage(lat: number, lon: number): boolean {
  const de = getCountryBoundingBox("DE");
  if (!de) return false;
  return (
    lat >= de.minLat - DWD_COVERAGE_BUFFER_DEG &&
    lat <= de.maxLat + DWD_COVERAGE_BUFFER_DEG &&
    lon >= de.minLon - DWD_COVERAGE_BUFFER_DEG &&
    lon <= de.maxLon + DWD_COVERAGE_BUFFER_DEG
  );
}

